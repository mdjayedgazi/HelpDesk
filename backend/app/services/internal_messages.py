"""Business rules for the Owner Inbox internal-messaging channel.

Only the single OWNER composes messages and browses the recipient directory;
addressed AGENT/ADMIN recipients may list and mark read their own rows. Every
rule here is enforced server-side - the frontend only mirrors these decisions.
"""

import uuid
from datetime import datetime, timezone

from fastapi import HTTPException, status
from sqlmodel import select
from sqlmodel.ext.asyncio.session import AsyncSession

from app.enums.enums import InternalAudience, NotificationType, Role
from app.models.internal_message import InternalMessage, InternalMessageRecipient
from app.models.notification import Notification
from app.models.user import User
from app.services.notifications import create_notification

# Body preview length used by the sent/inbox lists.
PREVIEW_LENGTH = 140

# Only active agents and administrators are eligible recipients. Customers and
# the Owner are never addressed (the Owner is the author; customers are outside
# the internal channel entirely).
ELIGIBLE_ROLES: tuple[Role, ...] = (Role.AGENT, Role.ADMIN)


async def resolve_recipients(
    session: AsyncSession,
    *,
    audience: InternalAudience,
    recipient_user_id: uuid.UUID | None,
) -> list[User]:
    """Expand an audience into the concrete, eligible recipient accounts.

    Raises a clear HTTP error instead of silently succeeding when nothing can
    be addressed. The result is ordered so the stored recipient list - and any
    page of it - is stable across requests.
    """
    if audience == InternalAudience.INDIVIDUAL:
        # The schema guarantees a non-null id for this audience; re-check so
        # the service is safe to call directly (e.g. from tests).
        if recipient_user_id is None:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
                detail="An individual message needs a recipient",
            )
        recipient = await session.get(User, recipient_user_id)
        if recipient is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Recipient not found",
            )
        if not recipient.is_active or recipient.role not in ELIGIBLE_ROLES:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=(
                    "The selected recipient is not an active agent or "
                    "administrator"
                ),
            )
        return [recipient]

    roles = ELIGIBLE_ROLES
    if audience == InternalAudience.AGENTS:
        roles = (Role.AGENT,)
    elif audience == InternalAudience.ADMINS:
        roles = (Role.ADMIN,)

    statement = (
        select(User)
        .where(User.role.in_(roles), User.is_active.is_(True))
        .order_by(User.full_name.asc(), User.id.asc())
    )
    recipients = list((await session.exec(statement)).all())
    if not recipients:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="There are no eligible recipients for this audience",
        )
    return recipients


def create_message(
    session: AsyncSession,
    *,
    sender: User,
    audience: InternalAudience,
    subject: str,
    body: str,
    recipients: list[User],
) -> InternalMessage:
    """Stage the message and one recipient row per addressed employee.

    The caller commits, so the message and every recipient row are created in a
    single transaction. ``sender`` is the authenticated Owner - never a value
    from the request.
    """
    if not recipients:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="There are no eligible recipients for this audience",
        )

    message = InternalMessage(
        sender_user_id=sender.id,
        audience=audience,
        subject=subject,
        body=body,
        recipient_count=len(recipients),
    )
    session.add(message)

    # ``message.id`` is generated by the field default factory, so it is
    # available before the flush; every row below points at the same message.
    for recipient in recipients:
        session.add(
            InternalMessageRecipient(
                message_id=message.id,
                recipient_user_id=recipient.id,
                recipient_role_snapshot=recipient.role,
                recipient_full_name_snapshot=recipient.full_name,
                recipient_email_snapshot=recipient.email,
            )
        )
        # One notification per addressed employee, in the same transaction as
        # the recipient row. The body is never copied into the notification -
        # the employee opens the message to read it. A retry cannot duplicate
        # either row: the unique (message_id, recipient) constraint aborts the
        # whole transaction before commit.
        create_notification(
            session,
            recipient_user_id=recipient.id,
            related_internal_message_id=message.id,
            type=NotificationType.INTERNAL_MESSAGE_RECEIVED,
            title="New message from the Owner",
            message=(
                "The Owner sent you an internal message. Open it to read the "
                "details."
            ),
        )

    return message


async def mark_message_read(
    session: AsyncSession,
    *,
    message_id: uuid.UUID,
    reader: User,
) -> int:
    """Mark the reader's own recipient row read. Caller commits.

    A non-recipient gets ``404`` (never ``403``), so the API does not reveal
    that a message exists for somebody else.
    """
    row = (
        await session.exec(
            select(InternalMessageRecipient).where(
                InternalMessageRecipient.message_id == message_id,
                InternalMessageRecipient.recipient_user_id == reader.id,
            )
        )
    ).first()
    if row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Message not found",
        )

    if row.read_at is None:
        row.read_at = datetime.now(timezone.utc)
        session.add(row)
        # Keep the notification centre and the message's own read state
        # consistent: opening the message clears its notification's unread
        # badge in the same transaction.
        await _mark_message_notifications_read(
            session, message_id=message_id, reader_id=reader.id
        )
        return 1
    return 0


async def _mark_message_notifications_read(
    session: AsyncSession, *, message_id: uuid.UUID, reader_id: uuid.UUID
) -> None:
    """Mark the reader's own internal-message notifications read."""
    rows = (
        await session.exec(
            select(Notification).where(
                Notification.recipient_user_id == reader_id,
                Notification.related_internal_message_id == message_id,
                Notification.is_read.is_(False),
            )
        )
    ).all()
    for row in rows:
        row.is_read = True
        session.add(row)
